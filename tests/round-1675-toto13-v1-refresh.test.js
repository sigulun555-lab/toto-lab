'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const ROOT = process.cwd();
const REV_PATH = path.join(ROOT, 'predictions/round_1675_ChatGPT_shared_score_v1_revision_20261126T022833JST.jsonl');
const MANIFEST_PATH = path.join(ROOT, 'reports/round_1675_toto13_v1_revision_manifest_20261126T022833JST.json');
const PRIOR_PATH = path.join(ROOT, 'prior-input/predictions/round_1675_ChatGPT_shared_score_v1.jsonl');
const PRIOR_BLOB = 'e8b3be0316105de2e9fed804108ae14696ae2ce4';
function gitBlobSha(text) {
  const b = Buffer.from(text, 'utf8');
  return crypto.createHash('sha1').update(Buffer.concat([Buffer.from('blob ' + b.length + '\0'), b])).digest('hex');
}
const priorText = fs.readFileSync(PRIOR_PATH, 'utf8');
const priorRows = priorText.trim().split(/\r?\n/).filter(Boolean).map(JSON.parse);
const revisionText = fs.readFileSync(REV_PATH, 'utf8');
const rows = revisionText.trim().split(/\r?\n/).filter(Boolean).map(JSON.parse);
const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
const priorIds = new Set(priorRows.map(r => r.predictionId));
assert.equal(gitBlobSha(priorText), PRIOR_BLOB, 'previous V1 blob is unchanged');
assert.equal(priorRows.length, 13, 'previous V1 rows preserved');
assert.equal(rows.length, 13, 'revision contains 13 toto13 matches');
assert.deepEqual(rows.map(r => r.matchNumber), Array.from({length:13},(_,i)=>i+1));
assert.equal(new Set(rows.map(r=>r.predictionId)).size,13,'revision IDs unique');
assert.equal(new Set(rows.map(r=>r.revisionOf)).size,13,'revisionOf links unique');
assert.ok(rows.every(r=>priorIds.has(r.revisionOf)),'all revisions link to previous V1');
assert.ok(rows.every(r=>r.round===1675),'round 1675 only');
assert.ok(rows.every(r=>r.historyMatchesPerTeam===12),'12 historical matches per side');
assert.ok(rows.every(r=>Date.parse(r.predictionConfirmedAt)<Date.parse(r.deadlineAt)),'all revisions before deadline');
assert.ok(rows.every(r=>Math.abs(Object.values(r.outcomeProbabilities).reduce((a,b)=>a+b,0)-1)<=1e-7),'1X2 probability vectors normalize');
assert.ok(rows.every(r=>Math.abs(r.homeGoalProbabilities.reduce((a,b)=>a+b,0)-1)<=1e-7),'home goal probability vectors normalize');
assert.ok(rows.every(r=>Math.abs(r.awayGoalProbabilities.reduce((a,b)=>a+b,0)-1)<=1e-7),'away goal probability vectors normalize');
assert.ok(rows.every(r=>r.notes.includes('No market blend')),'no market blend in revision notes');
assert.ok(rows.every(r=>r.dataSource.includes('537 completed matches')),'data source records 537 completed matches');
assert.equal(manifest.product,'toto13');
assert.equal(manifest.round,1675);
assert.equal(manifest.previousPredictionRows,13);
assert.equal(manifest.revisionRows,13);
assert.equal(manifest.revisionOfCount,13);
assert.equal(manifest.history.completedMatches,537);
assert.equal(manifest.history.priorHistoryMatches,512);
assert.equal(manifest.history.newlyAvailableMatches,25);
assert.equal(manifest.history.removedPriorMatches,0);
assert.equal(manifest.history.sourceBlobSha,'3ddebaf4eeef4195ae89e942974bc3c505aa3235');
assert.equal(manifest.model.blobSha,'20cde0fc85016db3ef7abac7d2bb485510ba4e22');
assert.equal(manifest.parser.blobSha,'ef557e084cab802df7830d949bd1f52ddee5db7c');
assert.equal(manifest.aliases.blobSha,'5de22584524ff4c07ddac1d27f49afbbbc5f88ab');
assert.equal(manifest.marketSnapshot.used,false);
assert.equal(manifest.validation.actualExportedFunction,true);
console.log('Round 1675 toto13 V1 revision schema/provenance tests passed: 13/13 rows, 25 new history matches, 13 revisionOf links.');
